package com.scse.curriculum.syllabus.comparison.model;

/**
 * Academic text sections that may require semantic comparison.
 *
 * Numerical/structural fields such as credits, semester,
 * assessment percentage and mappings are intentionally excluded.
 */
public enum SemanticSectionType {

    COURSE_OBJECTIVE,

    CLO,

    TOPIC,

    TEACHING_METHOD,

    LEARNING_ACTIVITY,

    EXAM_REQUIREMENT
}